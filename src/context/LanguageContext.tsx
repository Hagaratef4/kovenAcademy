function readInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'ar'
  return window.localStorage.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'ar'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readInitialLanguage)
  const direction: 'rtl' | 'ltr' = language === 'ar' ? 'rtl' : 'ltr'

  useLayoutEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = direction
    document.title = language === 'ar' ? 'كوفن — تواصل • ساند • انمُ' : 'Koven — Connect • Support • Grow'
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]')
    if (description) {
      description.content = language === 'ar'
        ? 'كوفن — منصة تعليمية تربط الطلاب وأولياء الأمور بالمعلمين. تواصل • ساند • انمُ.'
        : 'Koven — an educational marketplace connecting students, parents, and teachers. Connect. Support. Grow.'
    }
  }, [direction, language])

  const setLanguage = useCallback((nextLanguage: Language) => {
    window.localStorage.setItem(LANGUAGE_KEY, nextLanguage)
    setLanguageState(nextLanguage)
  }, [])

  const t = useCallback((text: string, values: TranslationValues = {}) => {
    let result = text
    if (language === 'ar') {
      const phoneLength = text.match(/^(.+) numbers should be (.+)\.$/)
      if (phoneLength) {
        const expected = phoneLength[2]
          .replace(/^(\d+)–(\d+) digits$/, '$1 إلى $2 أرقام')
          .replace(/^(\d+) digits$/, '$1 أرقام')
        result = `يجب أن يتكوّن رقم ${arabic[phoneLength[1]] ?? phoneLength[1]} من ${expected}.`
      } else {
        result = arabic[text] ?? text
      }
    }
    for (const [key, value] of Object.entries(values)) {
      result = result.replaceAll(`{${key}}`, String(value))
    }
    return result
  }, [language])

  const value = useMemo(() => ({ language, direction, setLanguage, t }), [language, direction, setLanguage, t])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
